//! The EXIF tags, by IFD: their names (as EXIF 3.0 and TIFF 6.0 give them, and exiftool
//! shows them) and numbers, for showing them and for scripts naming them.

use super::exif::Ifd;

/// A tag known by name: where it goes, its number, its name.
pub struct Tag {
    pub ifd: Ifd,
    pub tag: u16,
    pub name: &'static str,
}

const fn t(ifd: Ifd, tag: u16, name: &'static str) -> Tag {
    Tag { ifd, tag, name }
}

