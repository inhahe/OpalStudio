/// Tag `tag`'s name in `ifd` (the thumbnail's IFD taking IFD0's names), or its number as
/// `0xNNNN` if unknown.
pub fn name(ifd: Ifd, tag: u16) -> String {
    let ifd = if ifd == Ifd::Thumbnail { Ifd::Image } else { ifd };
    TAGS.iter().find(|t| t.ifd == ifd && t.tag == tag).map_or_else(|| format!("0x{tag:04X}"), |t| t.name.to_owned())
}

/// The tag `name` names, and its IFD: a name above, or a number (`0xNNNN`) in `ifd`.
pub fn named(name: &str, ifd: Option<Ifd>) -> Option<(Ifd, u16)> {
    if let Some(hex) = name.strip_prefix("0x").or_else(|| name.strip_prefix("0X")) {
        return Some((ifd?, u16::from_str_radix(hex, 16).ok()?));
    }
    TAGS.iter().find(|t| t.name.eq_ignore_ascii_case(name) && ifd.is_none_or(|i| i == t.ifd)).map(|t| (t.ifd, t.tag))
}
